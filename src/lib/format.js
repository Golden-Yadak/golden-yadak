// =============================================================
//  ابزارهای قالب‌بندی اعداد و قیمت (فارسی/تومان)
//  قیمت‌ها در داده به‌صورت عددی (تومان) ذخیره می‌شن و فقط موقع
//  نمایش به فرمت فارسی تبدیل می‌شن. این الگو با پاسخ API واقعی
//  (که عدد برمی‌گردونه) هم‌خوان است.
// =============================================================

const PERSIAN_DIGITS = ["۰", "۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹"];

// تبدیل ارقام لاتین به فارسی (ورودی می‌تونه عدد یا رشته باشه)
export function toPersianDigits(input) {
  return String(input).replace(/\d/g, (d) => PERSIAN_DIGITS[Number(d)]);
}

// قالب‌بندی قیمت تومان: 1250000 -> "۱,۲۵۰,۰۰۰"
export function formatToman(value) {
  const num = Number(value) || 0;
  return toPersianDigits(num.toLocaleString("en-US"));
}
